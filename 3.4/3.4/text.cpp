//        代码区是共享的，共享的目的是对于频繁被执行的程序，只需要在内存中有一份代码即可
//        代码区是只读的，使其只读的原因是防止程序意外地修改了他的指令

//全局区：存放全局变量和静态变量及常量---改区域的数据在程序结束后由操作系统释放



