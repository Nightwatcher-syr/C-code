//堆区：由程序员分配和存放，若程序员不释放，程序结束时由操作系统回收
//在C++中主要用new在堆区开辟内存



int* func()
{
	//利用NEW关键字可以将数据开辟到堆区
	//指针  本质上也是局部变量，放在栈上，指针保存的数据是放在堆区
	int*p=new int(10);    //用new关键字

	return p;
}
int main()
{
	
	int* p = func();
	cout << *p << endl;
	cout << *p << endl;
	cout << *p << endl;
	cout << *p << endl;   //不把堆区的内存



	return 0;
}