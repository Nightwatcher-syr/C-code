//1.内存分区模型
//代码区：存放函数的二进制代码，由操作系统进行管理
//全局区：存放全局变量和静态变量即常量
//栈区：由编译器自动分配释放，存放函数的参数值，局部变量等
//堆区：由程序员分配和存放，若程序员不释放，程序结束时由操作系统回收


//内存四区的意义
//不同区域存放的数据，赋予不同的生命周期，给我们更大灵活编程




//生成了exe可执行程序，未执行程序前分为两个区域（即代码区和全局区都是程序运行前就有的）


